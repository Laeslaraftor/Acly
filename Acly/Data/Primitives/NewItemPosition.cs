namespace Acly
{
    /// <summary>
    /// Позиция на которую будет добавлен новый элемент
    /// </summary>
    public enum NewItemPosition
    {
        /// <summary>
        /// Позиция по умолчанию (обычно самое начало)
        /// </summary>
        None = 0,
        /// <summary>
        /// В начале
        /// </summary>
        AtBeginning = 1,
        /// <summary>
        /// В конце
        /// </summary>
        AtEnd = 2
    }
}
